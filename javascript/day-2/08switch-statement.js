// Example of Traffic Lights

let color = "red";

switch (color) {
  case "red":
    console.log("STOP");
  // break;

  case "yellow":
    console.log("WAIT");
  // break;

  case "green":
    console.log("GOOOOOOOOOOO");
  // break;

  default:
    console.log("NOT THE VALID COLOR.");
}

