let size = "L"; 

if(size == "XL")
{
    console.log("Price is : Rs. 250");
}


else if(size == "L")
{
    console.log("Price is : Rs. 200");
}


else if(size == "M")
{
    console.log("Price is : Rs. 150");
}


else if(size == "S")
{
    console.log("Price is : Rs. 100");
}

else
{
    console.log("Invalid Size.\nSizes are (XL, L , M , S)");
}